const cache = new Map();
// two frames, the second one a pixel lower (a cheap walk bob), like the other enemies
export function bossSprite(id) {
  let s = cache.get(id);
  if (!s) {
    const [pal, fn] = ART[id], f0 = make(32, 26, (x) => fn(x, ...pal)), f1 = document.createElement('canvas');
    f1.width = f0.width; f1.height = f0.height + 1; f1.getContext('2d').drawImage(f0, 0, 1);
    s = [f0, f1]; cache.set(id, s);
  }
  return s;
}
